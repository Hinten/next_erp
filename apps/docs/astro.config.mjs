import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import mermaid from 'astro-mermaid';
import mermaidZoom from './mermaid-zoom.mjs';

export default defineConfig({
  integrations: [
    // Must precede starlight() so it transforms ```mermaid fences into rendered
    // SVG before Starlight's Expressive Code claims the code blocks. `autoTheme`
    // follows the docs light/dark toggle.
    mermaid({ theme: 'default', autoTheme: true }),
    // Adds pan/zoom (⛶ button + full-screen overlay) to the diagrams mermaid
    // renders. Order after mermaid() is cosmetic — it enhances at runtime.
    mermaidZoom(),
    starlight({
      title: 'Delfrance',
      description: 'Open-source ERP — Next.js rewrite docs.',
      // The default locale is served at the site root (no `/pt-br/` prefix) —
      // content lives directly under `src/content/docs/`, not in a locale
      // subfolder. Starlight's `root` locale key is exactly this case; keying it
      // `pt-br` instead made the sidebar link to `/pt-br/...` (404) and left the
      // autogenerated groups empty. English is additive under `/en/`.
      defaultLocale: 'root',
      locales: {
        root: { label: 'Português', lang: 'pt-BR' },
        en: { label: 'English' },
      },
      sidebar: [
        {
          label: 'Getting started',
          items: [
            { label: 'Overview', link: '/getting-started/overview/' },
            { label: 'Local setup', link: '/getting-started/local-setup/' },
            { label: 'Running tests', link: '/getting-started/running-tests/' },
          ],
        },
        {
          label: 'Architecture',
          items: [{ autogenerate: { directory: 'architecture' } }],
        },
        {
          label: 'Architecture decisions',
          items: [{ autogenerate: { directory: 'adr' } }],
        },
        {
          label: 'Guides',
          items: [{ autogenerate: { directory: 'guides' } }],
        },
      ],
    }),
  ],
});
